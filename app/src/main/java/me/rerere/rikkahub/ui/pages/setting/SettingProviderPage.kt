@Composable
fun SettingProviderPage(vm: SettingVM = koinViewModel()) {
    val settings by vm.settings.collectAsStateWithLifecycle()
    val navController = LocalNavController.current
    SettingProviderPageContent(
        providers = settings.providers,
        onProvidersChange = { vm.updateSettings(settings.copy(providers = it)) },
        onOpenProvider = { navController.navigate(Screen.SettingProviderDetail(providerId = it.toString())) },
    )
}

/** Original provider list, reusable without acquiring or mutating SettingsStore. */
@Composable
fun SettingProviderPageContent(
    providers: List<ProviderSetting>,
    onProvidersChange: (List<ProviderSetting>) -> Unit,
    onOpenProvider: (Uuid) -> Unit,
    onBack: (() -> Unit)? = null,
    allowRecommendations: Boolean = true,
    allowImport: Boolean = true,
    configureOptions: ProviderConfigureOptions = ProviderConfigureOptions(),
    enabled: Boolean = true,
    onProvidersChangeConfirmed: ((List<ProviderSetting>, (Boolean) -> Unit) -> Unit)? = null,
) {
    val scrollBehavior = TopAppBarDefaults.exitUntilCollapsedScrollBehavior()
    var searchQuery by remember { mutableStateOf("") }
    val lazyListState = rememberLazyListState()
    val reorderableState = rememberReorderableLazyListState(lazyListState) { from, to ->
        val fromIndex = providers.indexOfFirst { it.id == from.key }
        val toIndex = providers.indexOfFirst { it.id == to.key }
        if (enabled && fromIndex >= 0 && toIndex >= 0) {
            val newProviders = providers.toMutableList().apply { add(toIndex, removeAt(fromIndex)) }
            onProvidersChange(newProviders)
        }
    }

    val filteredProviders = remember(providers, searchQuery) {
        if (searchQuery.isBlank()) {
            providers
        } else {
            providers.filter { provider ->
                provider.name.contains(searchQuery, ignoreCase = true)
            }
        }
    }

    Scaffold(
        topBar = {
            LargeFlexibleTopAppBar(
                title = {
                    Text(text = stringResource(R.string.setting_provider_page_title))
                },
                navigationIcon = {
                    BackButton(onBack = onBack)
                },
                actions = {
                    if (allowRecommendations) RecommendProviderButton(onAddConfirmed = onProvidersChangeConfirmed?.let { commit ->
                        { provider, complete -> if (enabled) commit(listOf(provider.copyProvider(Uuid.random())) + providers, complete) else complete(false) }
                    }) { provider ->
                        if (enabled) onProvidersChange(listOf(provider.copyProvider(Uuid.random())) + providers)
                    }
                    if (allowImport) ImportProviderButton(onAddConfirmed = onProvidersChangeConfirmed?.let { commit ->
                        { provider, complete -> if (enabled) commit(listOf(provider.copyProvider(Uuid.random())) + providers, complete) else complete(false) }
                    }) {
                        if (enabled) onProvidersChange(listOf(it.copyProvider(Uuid.random())) + providers)
                    }
                    AddButton(configureOptions = configureOptions, enabled = enabled,
                        onAddConfirmed = onProvidersChangeConfirmed?.let { commit ->
                            { provider: ProviderSetting, complete: (Boolean) -> Unit -> commit(listOf(provider) + providers, complete) }
                        }) {
                        onProvidersChange(listOf(it) + providers)
                    }
                },
                scrollBehavior = scrollBehavior,
                colors = CustomColors.topBarColors
            )
        },
        modifier = Modifier.nestedScroll(scrollBehavior.nestedScrollConnection),
        containerColor = CustomColors.topBarColors.containerColor,
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(top = innerPadding.calculateTopPadding())
        ) {
            // Search bar
            OutlinedTextField(
                value = searchQuery,
                onValueChange = { searchQuery = it },
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 8.dp),
                placeholder = { Text(stringResource(R.string.setting_provider_page_search_providers)) },
                leadingIcon = {
                    Icon(HugeIcons.Search01, contentDescription = null)
                },
                trailingIcon = {
                    if (searchQuery.isNotEmpty()) {
                        IconButton(onClick = { searchQuery = "" }) {
                            Icon(HugeIcons.Cancel01, contentDescription = "Clear")
                        }
                    }
                },
                singleLine = true,
                shape = CircleShape,
            )


            LazyColumn(
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f)
                    .imePadding(),
                contentPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp) +
                    PaddingValues(bottom = innerPadding.calculateBottomPadding()),
                verticalArrangement = Arrangement.spacedBy(8.dp),
                state = lazyListState,
            ) {
                items(filteredProviders, key = { it.id }) { provider ->
                    ReorderableItem(
                        state = reorderableState,
                        key = provider.id
                    ) { isDragging ->
                        ProviderItem(
                            modifier = Modifier
                                .scale(if (isDragging) 0.95f else 1f)
                                .fillMaxWidth(),
                            provider = provider,
                            dragHandle = {
                                val haptic = LocalHapticFeedback.current
                                IconButton(
                                    onClick = {},
                                    enabled = enabled,
                                    modifier = Modifier
                                        .longPressDraggableHandle(
                                            onDragStarted = {
                                                haptic.performHapticFeedback(HapticFeedbackType.GestureThresholdActivate)
                                            },
                                            onDragStopped = {
                                                haptic.performHapticFeedback(HapticFeedbackType.GestureEnd)
                                            }
                                        )
                                ) {
                                    Icon(
                                        imageVector = HugeIcons.DragDropHorizontal,
                                        contentDescription = null
                                    )
                                }
                            },
                            onClick = {
                                if (enabled) onOpenProvider(provider.id)
                            }
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun RecommendProviderButton(
    onAddConfirmed: ((ProviderSetting, (Boolean) -> Unit) -> Unit)? = null,
    onAdd: (ProviderSetting) -> Unit
) {
    val toaster = LocalToaster.current
    var showSheet by remember { mutableStateOf(false) }
    val importSuccessMessage = stringResource(R.string.setting_provider_page_import_success)

    IconButton(
        onClick = { showSheet = true }
    ) {
        Icon(HugeIcons.Sparkles, contentDescription = stringResource(R.string.setting_provider_page_recommend))
    }

    if (showSheet) {
        ModalBottomSheet(
            onDismissRequest = { showSheet = false },
            sheetState = rememberBottomSheetState(
                initialValue = SheetValue.Hidden,
                enabledValues = setOf(SheetValue.Hidden, SheetValue.Expanded)
            )
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp)
                    .padding(bottom = 16.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                Text(
                    text = stringResource(R.string.setting_provider_page_recommend),
                    style = MaterialTheme.typography.titleLarge,
                    modifier = Modifier.padding(bottom = 4.dp)
                )
                RECOMMENDED_PROVIDERS.forEach { provider ->
                    RecommendProviderItem(
                        provider = provider,
                        onAdd = {
                            val complete: (Boolean) -> Unit = { accepted -> if (accepted) toaster.show(importSuccessMessage, type = ToastType.Success) }
                            if (onAddConfirmed != null) onAddConfirmed(provider, complete)
                            else { onAdd(provider); complete(true) }
                        }
                    )
                }
            }
        }
    }
}

