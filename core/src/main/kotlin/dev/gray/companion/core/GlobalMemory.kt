package dev.gray.companion.core

import kotlinx.serialization.Serializable

/** Global policy only. All generated summaries still belong to Session.historyMemory. */
@Serializable data class GlobalMemoryConfig(
    val enabled: Boolean = false,
    val extensionId: String? = null,
    val legacyLeafWorkflowIds: List<String> = emptyList(),
    val credentialOwnerAliases: Map<String, String> = emptyMap(),
    val smallSummaryXmlTag: String = "summary",
    val largeSummaryXmlTag: String = "summary",
    val xmlValidationVersion: Int = 0
)

/** Both stages count original BODY messages, including the sources covered by small summaries. */
@Serializable data class MemoryStageRules(
    val protectFirstFloors: Int = 0,
    val minimumNewFloors: Int = 200,
    val keepRecentFloors: Int = 40,
    val maximumBatchFloors: Int? = 200
)

data class GlobalMemoryDraft(
    val config: GlobalMemoryConfig,
    val extension: ConfigurationExtension,
    val group: CallGroup,
    val processor: HistoryProcessor,
    val smallNode: WorkflowNode,
    val largeNode: WorkflowNode,
    val largeRules: MemoryStageRules,
    val generation: ModelCallOptions,
    val reasoningParsing: ReasoningParsingConfig?
)

/** Accepted prompt provenance; generated by the compiler/engine, never trusted from a handler. */
@Serializable data class HistoryPromptRead(
    val sources: List<HistorySourceRef> = emptyList(),
    val childSegmentIds: List<String> = emptyList()
)

object GlobalMemory {
    /** Explicit live-only upgrade: accepted/frozen worlds are never passed here. */
    fun ensureXmlValidation(library: Library): Library {
        val draft = draft(library) ?: return library
        if (draft.config.xmlValidationVersion >= 1) return library
        fun protocol(node: WorkflowNode) = node.copy(blocks = node.blocks + PromptBlock(
            title = "摘要 XML 输出协议", template = "最终摘要必须放在唯一一对 <{{state.memory_summary_xml_tag}}> 与 </{{state.memory_summary_xml_tag}}> 标签中。标签内部只写非空摘要正文，不包含子标签；可用 XML 转义或 CDATA 表示特殊字符。不要输出第二份摘要。"))
        val targets = setOf(draft.smallNode.id, draft.largeNode.id)
        val flows = setOfNotNull(draft.processor.workflow.id, draft.processor.aggregationWorkflow?.id)
        return library.copy(memoryConfig = draft.config.copy(xmlValidationVersion = 1), groups = library.groups.map { group ->
            if (group.id != draft.group.id) group else group.copy(workflows = group.workflows.map { flow ->
                if (flow.id !in flows) flow else flow.copy(nodes = flow.nodes.map { node ->
                    if (node.id in targets) protocol(node) else node
                })
            })
        })
    }

    /** Only the actual summary-producing model receives this mandatory output contract. */
    internal fun summaryXmlTag(library: Library, workflowId: String, nodeId: String, executionVersion: Int): String? {
        if (executionVersion < 23) return null
        val config = library.memoryConfig ?: return null
        val processor = extension(library)?.let { MemoryPlugins.processor(library, it) } ?: return null
        return when {
            workflowId == processor.workflow.id && modelNode(processor.workflow, processor.outputKey)?.id == nodeId -> config.smallSummaryXmlTag
            workflowId == processor.aggregationWorkflow?.id && processor.aggregationWorkflow?.let { modelNode(it)?.id } == nodeId -> config.largeSummaryXmlTag
            else -> null
        }
    }

    fun credentialOwner(library: Library, ownerId: String): String =
        library.memoryConfig?.credentialOwnerAliases?.get(ownerId) ?: ownerId

    fun credentialSlot(library: Library, slot: CredentialSlot): CredentialSlot =
        slot.copy(ownerId = credentialOwner(library, slot.ownerId))

    fun extension(library: Library): ConfigurationExtension? = library.memoryConfig?.extensionId?.let { id ->
        library.extensions.firstOrNull { it.id == id && it.memory != null }
    }

    fun familyIds(library: Library, leafId: String): Set<String> =
        if (extension(library)?.memory?.workflowId == leafId)
            library.memoryConfig!!.legacyLeafWorkflowIds.toSet() + leafId else setOf(leafId)

    internal fun segments(library: Library?, session: Session, main: MainCall,
                          kind: HistorySourceKind = HistorySourceKind.DISPLAY): Map<String, HistoryMemorySegment> =
        HistoryMemory.effectiveSegments(session, main, kind, library?.memoryConfig?.legacyLeafWorkflowIds.orEmpty().toSet())

    internal fun inFamily(hierarchy: HistoryHierarchy, id: String, library: Library, leafId: String): Boolean =
        familyIds(library, leafId).any { hierarchy.belongsToFamily(id, it) } ||
            hierarchy.belongsToFamilies(id, familyIds(library, leafId))

    /** Find the model that really feeds the configured producer; preserve all custom dependency nodes. */
    fun modelNode(workflow: Workflow, outputKey: String? = null): WorkflowNode? {
        val models = ActionRegistry.defaults().descriptors().filter { it.usesModel }.mapTo(mutableSetOf()) { it.id }
        val nodes = workflow.nodes.associateBy { it.id }
        val seen = mutableSetOf<String>()
        fun find(node: WorkflowNode): WorkflowNode? {
            if (!seen.add(node.id)) return null
            if (node.actionId in models) return node
            return node.dependsOn.asReversed().firstNotNullOfOrNull { nodes[it]?.let(::find) }
        }
        val producer = if (outputKey == null) workflow.nodes.lastOrNull { it.actionId == "history.memory.write" }
            ?: workflow.nodes.lastOrNull() else workflow.nodes.lastOrNull { it.outputKey == outputKey }
        return producer?.let(::find) ?: workflow.nodes.lastOrNull { it.actionId in models }
    }

    fun draft(library: Library): GlobalMemoryDraft? {
        val config = library.memoryConfig ?: return null
        val extension = extension(library) ?: return null
        val group = library.groups.firstOrNull { it.id == extension.memory?.groupId } ?: return null
        val processor = MemoryPlugins.processor(library, extension) ?: return null
        val small = modelNode(processor.workflow, processor.outputKey) ?: return null
        val aggregate = processor.aggregationWorkflow ?: return null
        val large = modelNode(aggregate) ?: return null
        val select = aggregate.nodes.firstOrNull { it.actionId == "history.memory.select" }
        val rules = select?.let(::stageRules) ?: MemoryStageRules()
        return GlobalMemoryDraft(config, extension, group, processor, small, large, rules,
            small.generation.copy(profileId = small.generation.profileId ?: processor.workflow.modelProfileId),
            small.reasoningParsing)
    }

    /** Adopt source-field edits without turning editable workflows into a new ownership baseline. */
    fun adoptSourceDraft(current: GlobalMemoryDraft, candidate: Library): GlobalMemoryDraft? {
        val proposed = draft(candidate) ?: return null
        val projected = draft(withDraft(candidate, current)) ?: return null
        val ownedIds = listOf(current.processor.workflow.id, current.processor.aggregationWorkflow?.id)
        if (proposed.config != projected.config || proposed.extension != projected.extension ||
            proposed.group.workflows.map { it.id } != projected.group.workflows.map { it.id } ||
            proposed.group.copy(workflows = proposed.group.workflows.filterNot { it.id in ownedIds }) !=
            projected.group.copy(workflows = projected.group.workflows.filterNot { it.id in ownedIds }) ||
            proposed.smallNode.id != current.smallNode.id || proposed.largeNode.id != current.largeNode.id)
            return null
        // Either stage's native source editor may change the shared model settings.
        val largeGeneration = proposed.largeNode.generation.copy(profileId =
            proposed.largeNode.generation.profileId ?: proposed.processor.aggregationWorkflow?.modelProfileId)
        val smallChanged = proposed.generation != projected.generation || proposed.reasoningParsing != projected.reasoningParsing
        val largeChanged = largeGeneration != projected.generation || proposed.largeNode.reasoningParsing != projected.reasoningParsing
        if (smallChanged && largeChanged && (proposed.generation != largeGeneration ||
                proposed.reasoningParsing != proposed.largeNode.reasoningParsing)) return null
        return proposed.copy(config = current.config, extension = current.extension, group = current.group,
            generation = if (largeChanged) largeGeneration else proposed.generation,
            reasoningParsing = if (largeChanged) proposed.largeNode.reasoningParsing else proposed.reasoningParsing)
    }

    internal fun stageRules(node: WorkflowNode): MemoryStageRules = MemoryStageRules(
        node.arguments["protectFirstFloors"]?.toIntOrNull() ?: 0,
        node.arguments["minimumNewFloors"]?.toIntOrNull() ?: 200,
        node.arguments["keepRecentFloors"]?.toIntOrNull() ?: 40,
        if (node.arguments["maximumBatchFloors"] == Int.MAX_VALUE.toString()) null
            else node.arguments["maximumBatchFloors"]?.toIntOrNull() ?: 200
    )

    /** Explicit live migration only; never called by the wire decoder or frozen-world replay. */
    fun ensureGlobal(library: Library): ExtensionEditResult {
        if (library.memoryConfig != null && library.memoryConfig.extensionId == null) {
            val initialized = ensureGlobal(library.copy(memoryConfig = null))
            return initialized.copy(library = initialized.library?.let { next -> next.copy(memoryConfig =
                requireNotNull(next.memoryConfig).copy(enabled = false,
                    credentialOwnerAliases = library.memoryConfig.credentialOwnerAliases)) })
        }
        if (library.memoryConfig != null) return ExtensionEditResult(ensureXmlValidation(library))
        val session = library.sessions.firstOrNull { it.id == library.selectedSessionId }
        val native = library.extensions.filter { it.memory != null && MemoryPlugins.processor(library, it) != null }
        val chosen = native.firstOrNull { it.id in session?.enabledExtensionIds.orEmpty() } ?: native.firstOrNull()
        val legacy = library.mainCalls.firstOrNull { it.id == session?.mainCallId && it.history.processor.workflow.enabled }
            ?: library.mainCalls.firstOrNull { it.history.processor.workflow.enabled }
        val aliases = (native.mapNotNull { it.memory?.workflowId } +
            library.mainCalls.map { it.history.processor.workflow.id }).distinct()
        var base = library
        val definition: ConfigurationExtension
        if (chosen != null) definition = chosen else {
            val processor = legacy?.history?.processor ?: HistoryProcessor()
            val group = CallGroup(name = "记忆调用组", workflows = listOf(processor.workflow) + listOfNotNull(processor.aggregationWorkflow))
            definition = ConfigurationExtension(name = "记忆", resources = listOf(ExtensionResourceRef(ExtensionResourceKind.GROUP, group.id)),
                memory = MemoryPlugins.rules(group.id, processor))
            base = base.copy(groups = base.groups + group, extensions = base.extensions + definition,
                mainCalls = base.mainCalls.map { main -> if (main.id == legacy?.id)
                    main.copy(history = main.history.copy(processor = HistoryProcessor())) else main })
        }
        val old = requireNotNull(MemoryPlugins.processor(base, definition))
        val group = base.groups.first { it.id == definition.memory!!.groupId }
        val small = modelNode(old.workflow, old.outputKey)
            ?: return failure("memoryConfig", "旧记忆没有可编辑的模型来源；原调用与摘要已保留")
        var aggregate = old.aggregationWorkflow ?: defaultHistoryAggregationWorkflow(old)
        val large = modelNode(aggregate) ?: return failure("memoryConfig", "旧大摘要没有可编辑的模型来源；原调用已保留")
        val readKeys = aggregate.nodes.filter { it.actionId == "history.memory.read" }.map { it.outputKey }
        fun editable(node: WorkflowNode, legacyInput: Set<String>): WorkflowNode {
            val implicit = if (node.includeHistory && !node.explicitHistory && node.blocks.none { isStructuredHistoryBlock(it.template) })
                listOf(PromptBlock(title = "历史正文", template = "{{history.display}}")) else emptyList()
            val inputBlock = if (node.inputTemplate.isNotBlank() || node.inputProcessing.isNotEmpty()) listOf(
                PromptBlock(title = "摘要输入", role = Role.USER, position = PromptPosition.AFTER_HISTORY,
                    template = if (node.inputTemplate.trim() in legacyInput) "{{history.display}}" else node.inputTemplate,
                    processing = emptyList())) else emptyList()
            return node.copy(inputTemplate = "", inputProcessing = emptyList(), includeHistory = false, explicitHistory = true,
                blocks = node.blocks + implicit + inputBlock)
        }
        val generation = small.generation.copy(profileId = small.generation.profileId ?: old.workflow.modelProfileId)
        val smallEdited = editable(small, setOf("{{history.pending}}"))
        val largeEdited = editable(large, readKeys.map { "{{result.$it}}" }.toSet())
            .copy(generation = generation, reasoningParsing = small.reasoningParsing)
        aggregate = aggregate.copy(enabled = true, afterWorkflowId = old.workflow.id,
            nodes = aggregate.nodes.map { node -> when {
                node.id == large.id -> largeEdited
                node.actionId == "history.memory.select" -> node.copy(arguments = node.arguments + stageArguments(MemoryStageRules()))
                node.actionId == "history.memory.write" -> node.copy(arguments = node.arguments + ("source" to "{{history.display}}"))
                else -> node
            } })
        val processor = old.copy(sourceKind = HistorySourceKind.DISPLAY, thresholdBasis = HistoryThresholdBasis.UNCOMPRESSED_FLOORS,
            maximumBatchFloors = old.maximumBatchFloors ?: old.minimumNewFloors,
            workflow = old.workflow.copy(enabled = true, nodes = old.workflow.nodes.map { if (it.id == small.id) smallEdited else it }),
            aggregationWorkflow = aggregate)
        base = MemoryPlugins.withProcessor(base, definition, group, processor).copy(memoryConfig = GlobalMemoryConfig(
            enabled = if (chosen == null) legacy?.history?.processor?.workflow?.enabled == true else
                library.sessions.any { chosen.id in it.enabledExtensionIds },
            extensionId = definition.id, legacyLeafWorkflowIds = (aliases + processor.workflow.id).distinct()))
        return finish(ensureXmlValidation(base), "统一全局记忆配置；旧输入与隐式历史已转为可编辑提示块，当前摘要模型不再使用输入正则；保留各聊天摘要、来源及旧环境")
    }

    private fun stageArguments(rules: MemoryStageRules): Map<String, String> = mapOf(
        "source" to "{{history.display}}", "mode" to "UNMERGED_LEAVES",
        "protectFirstFloors" to rules.protectFirstFloors.toString(),
        "minimumNewFloors" to rules.minimumNewFloors.toString(),
        "keepRecentFloors" to rules.keepRecentFloors.toString(),
        "maximumBatchFloors" to (rules.maximumBatchFloors ?: Int.MAX_VALUE).toString()
    )

    fun withDraft(library: Library, draft: GlobalMemoryDraft): Library {
        fun edited(old: WorkflowNode, edited: WorkflowNode) = old.copy(blocks = edited.blocks,
            outputProcessing = edited.outputProcessing, regexOutputCopy = edited.regexOutputCopy,
            generation = draft.generation, reasoningParsing = draft.reasoningParsing)
        val leaf = draft.processor.workflow.copy(modelProfileId = draft.generation.profileId, nodes = draft.processor.workflow.nodes.map { node ->
            if (node.id == draft.smallNode.id) edited(node, draft.smallNode) else node
        })
        val aggregate = requireNotNull(draft.processor.aggregationWorkflow).let { flow -> flow.copy(modelProfileId = draft.generation.profileId, nodes = flow.nodes.map { node ->
            when {
                node.id == draft.largeNode.id -> edited(node, draft.largeNode)
                node.actionId == "history.memory.select" -> node.copy(arguments = node.arguments + stageArguments(draft.largeRules))
                else -> node
            }
        }) }
        val processor = draft.processor.copy(sourceKind = HistorySourceKind.DISPLAY,
            thresholdBasis = HistoryThresholdBasis.UNCOMPRESSED_FLOORS, workflow = leaf, aggregationWorkflow = aggregate)
        return MemoryPlugins.withProcessor(library, draft.extension, draft.group, processor).copy(memoryConfig = draft.config)
    }

    fun update(library: Library, expected: GlobalMemoryDraft, draft: GlobalMemoryDraft): ExtensionEditResult {
        if (library.memoryConfig != expected.config || library.extensions.firstOrNull { it.id == expected.extension.id } != expected.extension ||
            library.groups.firstOrNull { it.id == expected.group.id } != expected.group)
            return failure("memoryConfig", "记忆配置已改变，请重新打开后保存")
        if (draft.config.copy(smallSummaryXmlTag = expected.config.smallSummaryXmlTag,
                largeSummaryXmlTag = expected.config.largeSummaryXmlTag) != expected.config || draft.extension != expected.extension || draft.group != expected.group ||
            draft.processor.workflow.id != expected.processor.workflow.id || draft.smallNode.id != expected.smallNode.id ||
            draft.largeNode.id != expected.largeNode.id || draft.processor.aggregationWorkflow?.id != expected.processor.aggregationWorkflow?.id)
            return failure("memoryConfig", "记忆编辑不能替换所属调用或全局开关")
        return finish(withDraft(library, draft), "保存全局记忆；新回合使用更新后的配置")
    }

    fun setEnabled(library: Library, expected: GlobalMemoryConfig, enabled: Boolean): ExtensionEditResult {
        if (library.memoryConfig != expected) return failure("memoryConfig", "记忆开关已改变，请刷新后重试")
        return finish(library.copy(memoryConfig = expected.copy(enabled = enabled)),
            if (enabled) "为所有聊天开启记忆；摘要仍分别保存" else "关闭全局记忆活动；保留所有已保存摘要")
    }

    fun validate(library: Library): List<Issue> = buildList {
        val config = library.memoryConfig ?: return@buildList
        if (!SummaryXml.validTag(config.smallSummaryXmlTag)) add(Issue("memoryConfig.smallSummaryXmlTag", "小摘要 XML 标签名无效"))
        if (!SummaryXml.validTag(config.largeSummaryXmlTag)) add(Issue("memoryConfig.largeSummaryXmlTag", "大摘要 XML 标签名无效"))
        if (!config.enabled && config.extensionId == null) return@buildList
        val definition = extension(library)
        if (definition == null) { add(Issue("memoryConfig.extensionId", "全局记忆定义不存在")); return@buildList }
        val processor = MemoryPlugins.processor(library, definition)
        if (processor?.aggregationWorkflow == null) add(Issue("memoryConfig", "全局记忆须包含小摘要和大摘要"))
        if (processor?.sourceKind != HistorySourceKind.DISPLAY) add(Issue("memoryConfig", "全局记忆须使用展示正文"))
        if (config.legacyLeafWorkflowIds.any { it.isBlank() } || config.legacyLeafWorkflowIds.distinct().size != config.legacyLeafWorkflowIds.size)
            add(Issue("memoryConfig.legacyLeafWorkflowIds", "记忆来源家族不能重复或为空"))
        processor?.aggregationWorkflow?.nodes?.filter { it.actionId == "history.memory.select" }?.forEach { node ->
            val rules = stageRules(node)
            if (rules.minimumNewFloors < 1 || rules.keepRecentFloors < 0 || rules.protectFirstFloors < 0 ||
                rules.maximumBatchFloors?.let { it < 1 } == true) add(Issue("memoryConfig.largeRules", "大摘要楼层范围无效"))
        }
    }

    /** New-turn policy and scheduling image; invocation dependencies remain in their own captured view. */
    fun overlayGlobal(live: Library, frozen: Library, session: Session): Library {
        val config = live.memoryConfig ?: return frozen
        if (!config.enabled) return frozen.copy(memoryConfig = config.copy(extensionId = null,
            credentialOwnerAliases = frozen.memoryConfig?.credentialOwnerAliases.orEmpty() + config.credentialOwnerAliases),
            memoryExecutionView = null)
        val definition = extension(live) ?: error("全局记忆定义不存在")
        val rules = requireNotNull(definition.memory)
        val ownedIds = setOfNotNull(rules.workflowId, rules.aggregationWorkflowId)
        // Keep actual session choices for current-character and loaded-resource references. The
        // captured closure is readable only; it does not add any owners to the scheduling image.
        val closure = CapturedResourceClosure.capture(live.copy(memoryExecutionView = null),
            session.copy(executableWorld = null, pendingRun = null), rootExtension = definition)
        val connectionIds = closure.connections.associate { value -> value.id to
            if (frozen.connections.any { it.id == value.id && it != value })
                "memory-${definition.id}-connection-${value.id}-${CompletedWorlds.fingerprint(LibraryFormat.json.encodeToString(ApiConnection.serializer(), value)).take(16)}"
            else value.id }
        val connections = closure.connections.map { it.copy(id = connectionIds.getValue(it.id)) }
        val remappedProfiles = closure.profiles.map { it.copy(apiConnectionId = it.apiConnectionId?.let { id -> connectionIds[id] ?: id }) }
        val profileIds = remappedProfiles.associate { value -> value.id to
            if (frozen.profiles.any { it.id == value.id && it != value })
                "memory-${definition.id}-profile-${value.id}-${CompletedWorlds.fingerprint(LibraryFormat.json.encodeToString(ModelProfile.serializer(), value)).take(16)}"
            else value.id }
        val profiles = remappedProfiles.map { it.copy(id = profileIds.getValue(it.id)) }
        fun remap(flow: Workflow): Workflow = flow.copy(
            modelProfileId = flow.modelProfileId?.let { profileIds[it] ?: it },
            nodes = flow.nodes.map { node -> node.copy(generation = node.generation.copy(
                profileId = node.generation.profileId?.let { profileIds[it] ?: it })) })
        val groups = closure.groups.map { it.copy(workflows = it.workflows.map(::remap)) }
        val aliases = frozen.memoryConfig?.credentialOwnerAliases.orEmpty() + config.credentialOwnerAliases +
            connectionIds.entries.filter { it.key != it.value }.associate { it.value to it.key } +
            profileIds.entries.filter { it.key != it.value }.associate { it.value to it.key }
        val policy = config.copy(credentialOwnerAliases = aliases)
        val resources = closure.copy(schemaVersion = LibraryFormat.CURRENT_VERSION,
            memoryConfig = policy, memoryExecutionView = null, groups = groups,
            mainCalls = closure.mainCalls.map { main -> main.copy(workflows = main.workflows.map(::remap),
                history = main.history.copy(processor = main.history.processor.copy(
                    workflow = remap(main.history.processor.workflow),
                    aggregationWorkflow = main.history.processor.aggregationWorkflow?.let(::remap)))) },
            selectedProfileId = closure.selectedProfileId?.let { profileIds[it] ?: it },
            profiles = profiles, connections = connections)
        val incoming = groups.single { it.id == rules.groupId }
        val oldGroup = frozen.groups.firstOrNull { it.id == rules.groupId }
        val oldOwned = frozen.extensions.filter { it.memory?.groupId == rules.groupId }
            .flatMap { listOfNotNull(it.memory?.workflowId, it.memory?.aggregationWorkflowId) }.toSet()
        // A shared owner may contain ordinary calls. Never refresh or introduce those calls.
        val scheduledGroup = (oldGroup ?: incoming.copy(workflows = emptyList(), boundPackageIds = emptyList(),
            tiles = emptyList(), stateDefaults = emptyMap())).copy(workflows =
                oldGroup?.workflows.orEmpty().filterNot { it.id in ownedIds || it.id in oldOwned } +
                    incoming.workflows.filter { it.id in ownedIds })
        // Only the owned memory group participates. Other current members remain readable in resources.
        val scheduledDefinition = definition.copy(resources = listOf(ExtensionResourceRef(ExtensionResourceKind.GROUP, rules.groupId)),
            parameters = emptyList())
        val scheduledGroups = frozen.groups.filterNot { it.id == rules.groupId } + scheduledGroup
        val referencedProfiles = (frozen.mainCalls.flatMap { it.configuredWorkflows() } + scheduledGroups.flatMap { it.workflows })
            .flatMap { flow -> listOfNotNull(flow.modelProfileId) + flow.nodes.mapNotNull { it.generation.profileId } }.toSet() +
                listOfNotNull(frozen.selectedProfileId)
        val oldAliases = frozen.memoryConfig?.credentialOwnerAliases.orEmpty().keys
        val retainedProfiles = frozen.profiles.filter { it.id !in oldAliases || it.id in referencedProfiles }
        val scheduledProfiles = retainedProfiles + profiles.filter { candidate ->
            candidate.id in referencedProfiles && retainedProfiles.none { it.id == candidate.id }
        }
        val connectionRefs = scheduledProfiles.mapNotNull { it.apiConnectionId }.toSet()
        val retainedConnections = frozen.connections.filter { it.id !in oldAliases || it.id in connectionRefs }
        val scheduledConnections = retainedConnections + connections.filter { candidate ->
            candidate.id in connectionRefs && retainedConnections.none { it.id == candidate.id }
        }
        val credentialOwners = (scheduledProfiles + profiles).map { it.id }.toSet() +
            (scheduledConnections + connections).map { it.id }
        val retainedPolicy = policy.copy(credentialOwnerAliases = aliases.filterKeys { it in credentialOwners })
        return frozen.copy(schemaVersion = LibraryFormat.CURRENT_VERSION, memoryConfig = retainedPolicy,
            memoryExecutionView = CapturedMemoryResources(resources.copy(memoryConfig = retainedPolicy), ownedIds),
            groups = scheduledGroups,
            extensions = frozen.extensions.filterNot { it.id == definition.id } + scheduledDefinition,
            profiles = scheduledProfiles, connections = scheduledConnections)

    }

    private fun finish(candidate: Library, change: String): ExtensionEditResult {
        val issues = LibraryValidator.validate(candidate).filter { it.error }.distinct()
        return ExtensionEditResult(candidate.takeIf { issues.isEmpty() }, issues, listOf(change))
    }
    private fun failure(path: String, message: String) = ExtensionEditResult(null, listOf(Issue(path, message)))
}
